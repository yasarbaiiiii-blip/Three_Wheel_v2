export function generateRoadSignLines(signType: RoadSignType, size: number): PlanLine[] {
    const data = SIGN_DATA[signType];
    if (!data) return [];
    const lines: PlanLine[] = [];
    let pointId = 1;
    for (let i = 0; i < data.length; i++) {
        const [x1, y1, x2, y2] = data[i];
        lines.push({
            id: `rs-${i}`,
            label: "Sign Line",
            layer: "marking",
            width: 0.1,
            from: { id: pointId++, x: x1 * size, y: y1 * size },
            to: { id: pointId++, x: x2 * size, y: y2 * size },
        });
    }
    return lines;
}
